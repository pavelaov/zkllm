// jtag_axi_0_stub.v : simulation/elaboration stand-in for the Xilinx JTAG-to-AXI Master IP (AXI4-Lite, 32-bit address/data). Idle master: never issues a transaction. Used only to check that sumfold_top elaborates; the real IP is generated by the implementation flow.
`timescale 1ns / 1ps
module jtag_axi_0 (
    input  wire        aclk,
    input  wire        aresetn,
    output wire [31:0] m_axi_awaddr,
    output wire [2:0]  m_axi_awprot,
    output wire        m_axi_awvalid,
    input  wire        m_axi_awready,
    output wire [31:0] m_axi_wdata,
    output wire [3:0]  m_axi_wstrb,
    output wire        m_axi_wvalid,
    input  wire        m_axi_wready,
    input  wire [1:0]  m_axi_bresp,
    input  wire        m_axi_bvalid,
    output wire        m_axi_bready,
    output wire [31:0] m_axi_araddr,
    output wire [2:0]  m_axi_arprot,
    output wire        m_axi_arvalid,
    input  wire        m_axi_arready,
    input  wire [31:0] m_axi_rdata,
    input  wire [1:0]  m_axi_rresp,
    input  wire        m_axi_rvalid,
    output wire        m_axi_rready
);
    assign m_axi_awaddr  = 32'd0;
    assign m_axi_awprot  = 3'd0;
    assign m_axi_awvalid = 1'b0;
    assign m_axi_wdata   = 32'd0;
    assign m_axi_wstrb   = 4'hF;
    assign m_axi_wvalid  = 1'b0;
    assign m_axi_bready  = 1'b1;
    assign m_axi_araddr  = 32'd0;
    assign m_axi_arprot  = 3'd0;
    assign m_axi_arvalid = 1'b0;
    assign m_axi_rready  = 1'b1;
endmodule

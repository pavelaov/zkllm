REPORT = {}

def f(x, nd=1, dash="--"):
    if x is None:
        return dash
    return f"{x:.{nd}f}"

def fi(x):
    return C.fmt_int(x) if x is not None else "--"

def emit(name: str, body: str, sources: list[str], status: str, notes=()):
    path = C.TABLES / f"{name}.tex"
    C.write_text(path, HEADER.format(ts=C.now_iso(), src=", ".join(sorted(set(sources)))) + body)
    REPORT[name] = {"file": C.rel(path), "status": status, "sources": sorted(set(sources)), "notes": list(notes)}
    print(f"[{status}] {C.rel(path)}")


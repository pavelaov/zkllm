def _idle(obj, subdir="kernels"):
    """(runner flag, effective flag): effective contention needs the runner flag AND no idle-probe evidence."""
    raw = bool(obj and (obj.get("contended") or any(d.get("contended") for d in obj.get("devices", []))))
    return raw, raw and not C.idle_verified(subdir)[0]


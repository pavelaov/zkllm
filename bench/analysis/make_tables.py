def _board_loads(campaign):
    """{(L, MHz, mode, n): max host CPU load (%) at the start of the step records of that configuration}."""
    import re
    out = {}
    for r in (campaign or {}).get("runs", []):
        m = re.match(r"L(\d+)_(\d+)_(auto|step)_n(\d+)", str(r.get("step", "")))
        if not m:
            continue
        k = (int(m.group(1)), int(m.group(2)), m.group(3), int(m.group(4)))
        ld = C.get(r, "contention_flags.host_cpu_load_pct")
        if ld is not None:
            out[k] = max(out.get(k, 0), ld)
    return out

